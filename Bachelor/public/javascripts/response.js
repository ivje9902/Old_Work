/**
 * Checks if the inputs are valid.
 * 
 * @param {String} questionType 
 * @param {Object} inputs 
 * @returns If any of the inputs are empty the function returns false
 */
function isValidInputs(questionType, inputs) {
    if (!questionType || !inputs) {
        return false;
    }
    return true;
}

/**
 * Returns the response from local storage. This function is only called if and identical request body exists in local storage.
 * Retrieves the answer from local storage and calls listener() to display the tips.
 * 
 * @param {JSOBObject} req_body The request body that consists of the input from the index page
 * @returns 
 */
function gptResponseFromLocalStorage(req_body) {
    const ans = JSON.parse(localStorage.getItem(req_body));
    console.log("Retrieved answer from local storage");
    console.log(ans);
    localStorage.setItem("req_body", req_body);

    const mode = ans.mode;
    const tipsToUse = mode === "no-RAG" ? ans.tips : ans.tipsRAG;

    for (let i = 1; i < 7; i++) {
        id = "tip_" + i;
        let tip = document.getElementById(id);
        description = document.getElementById("desc_" + i);
        tip.innerText = tipsToUse[i - 1].title;
        description.innerText = tipsToUse[i - 1].description;
    }
    const loader = document.getElementById("loader");
    const tips = document.getElementById("tips-container");

    loader.classList.add("hidden");
    tips.classList.remove("hidden");
    tips.classList.add("block");

    listener(tipsToUse);

    return;
}

/**
 * Saves the response from the API in local storage. The request body is used as the key and the answer is saved as a string.
 * 
 * @param {Object} req_body The request body that consists of the input from the index page
 * @param {Object} ans The answeer from the API
 */
function storeInLocalStorage(req_body, ans) {
    localStorage.setItem(req_body, JSON.stringify(ans));
    console.log(req_body, "Answer saved in local storage.");

}

/**
 * Checks if any of the checkboxes are checked. If any of them are checked the function returns true, otherwise false.
 * 
 * @param {Object} inputs All the tips and checkboxes
 * @returns {boolean} - If any of the checkboxes are checked
 */
function isCheckbox_true(inputs) {

    var cbox_checked = false;

    for (let i = 1; i < 7; i++) {
        if (inputs["cbox" + i] == "true") {
            cbox_checked = true;
        }
    }

    return cbox_checked;
}

