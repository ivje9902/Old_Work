/**
 * Checks what browser the user is using. This is used in generateDownload() as some browsers have different ways of downloading files.
 * 
 * @returns {String} - The name of the browser, or unknown, if it can't be determined
 */
function getBrowser() {
    if (navigator.userAgent.indexOf("Chrome") != -1) {
        return "Chrome";
    } else if (navigator.userAgent.indexOf("Opera") != -1) {
        return "Opera";
    } else if (navigator.userAgent.indexOf("MSIE") != -1) {
        return "IE";
    } else if (navigator.userAgent.indexOf("Firefox") != -1) {
        return "Firefox";
    } else {
        return "unknown";
    }
}

