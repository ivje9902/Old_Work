/**
 * Tries to send the feedback to the server using POST. If the request is successful it closes the form and alerts the user.
 * Otherwise it alerts the user that something went wrong.
 */
async function sendFeedback() {
    const form = document.getElementById("feedback-form");
    try {
        const formData = new FormData(form);
        const userText = form.querySelector("textarea").value; // Text from user
        formData.append("additional_info", userText);
        const data = Object.fromEntries(formData.entries());

        const response = await fetch(`/response/form`, {
            method: "POST",
            headers: {
                "Content-Type": "application/json",
            },
            body: JSON.stringify(data),
        });

        if (response.ok) {
            closeForm();
            alert("Tack för din feedback!");
        } else {
            alert("Något gick fel. Försök igen senare.");
        }
    } catch (error) {
        console.error("Error submitting feedback:", error);
    }
}