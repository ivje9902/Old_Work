/**
 * Handles the event of pressing the cards that contain the tips and checkboxes. Makes it possible to click the cards to check the boxes
 * 
 * @param {string} TARGET - What type of element was pressed
 * @param {string} ID - Which specific element was pressed
 */
function card_press(TARGET, ID) {
    checkbox = document.getElementById("cbox" + ID);

    if (checkbox.checked == true && TARGET != "INPUT") {
        checkbox.checked = false;
        checkbox.value = false;
    }
    else if (checkbox.checked == false && TARGET != "INPUT") {
        checkbox.checked = true;
        checkbox.value = true;
    }
}

/**
 * Opens the information container and displays the information about the results page.
 */
function open_information(ans) {
    const infoContainer = document.getElementById('information-container');

    if (ans == 'open') {
        console.log("Information button pressed, displaying information");
        infoContainer.classList.add('grid');
        infoContainer.classList.remove('hidden');
        infoContainer.focus();
    }
    else {
        const cookieValue = getCookie('response_infoBoxClosed');

        if (cookieValue) {
            console.log("Cookie found, not displaying information");
        }
        else {
            console.log("No cookie found, displaying information");
            infoContainer.classList.add('grid');
            infoContainer.classList.remove('hidden');
            infoContainer.focus();

        }

    }
}

/**
 * Hides the information container.
 */

function close_information(ans) {
    const infoContainer = document.getElementById('information-container');

    if (ans) {
        console.log("Visa ej igen, pressed, hiding information for 30 days");
        infoContainer.classList.add('hidden');
        infoContainer.classList.remove('grid');
        setCookie('response_infoBoxClosed', 'true', 30);
    }

    else {
        console.log("X, pressed, hiding information for 1 session");
        infoContainer.classList.add('hidden');
        infoContainer.classList.remove('grid');
        setCookie('response_infoBoxClosed', 'true');
    }
}


/**
 * Creates an eventlistener on the page that calls different functions depending on what element on the page was clicked.
 * 
 * @param {Object} tips - The tips genererated by the API
 */
function listener(tips) {
    open_information();

    document.addEventListener("click", (event) => {

        const ID = event.target.id;
        const TARGET = event.target.nodeName;
        const number_ID = ID.substring(ID.length - 1, ID.length);

        if (TARGET == "BUTTON" && ID != "evalButton" && ID != "download-button" && ID != "submit_button" && ID != "forever_close") {
            button_press(ID, tips);
        }
        else if ((TARGET == "DIV" || "H5" || "P" || "INPUT") && ["1", "2", "3", "4", "5", "6"].includes(number_ID)) {
            card_press(TARGET, number_ID);
        }
    });
}

